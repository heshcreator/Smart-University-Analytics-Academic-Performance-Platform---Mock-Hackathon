
-- SETTING UP THE CONTEXT


USE WAREHOUSE UNIVERSITY_WH;

USE DATABASE UNIVERSITY_DB;

USE SCHEMA UNIRAW;



-- CREATING STREAMS



-- STUDENT STREAM

CREATE OR REPLACE STREAM STUDENT_STREAM
ON TABLE STUDENT_RAW;


-- FACULTY STREAM

CREATE OR REPLACE STREAM FACULTY_STREAM
ON TABLE FACULTY_RAW;


-- COURSE STREAM

CREATE OR REPLACE STREAM COURSE_STREAM
ON TABLE COURSE_RAW;


-- EXAMINATION STREAM

CREATE OR REPLACE STREAM EXAMINATION_STREAM
ON TABLE EXAMINATION_RAW;


-- RESULT STREAM

CREATE OR REPLACE STREAM RESULT_STREAM
ON TABLE RESULT_RAW;


-- ATTENDANCE STREAM

CREATE OR REPLACE STREAM ATTENDANCE_STREAM
ON TABLE ATTENDANCE_RAW;



