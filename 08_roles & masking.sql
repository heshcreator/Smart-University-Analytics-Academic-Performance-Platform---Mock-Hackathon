-- SETTING CONTEXT


USE ROLE ACCOUNTADMIN;

USE WAREHOUSE UNIVERSITY_WH;

USE DATABASE UNIVERSITY_DB;



-- CREATE ROLES


CREATE OR REPLACE ROLE UNI_STUDENT_ROLE;

CREATE OR REPLACE ROLE UNIVERSITY_ADMIN_ROLE;




-- DATABASE ACCESS


GRANT USAGE
ON DATABASE UNIVERSITY_DB
TO ROLE UNI_STUDENT_ROLE;


GRANT USAGE
ON DATABASE UNIVERSITY_DB
TO ROLE UNIVERSITY_ADMIN_ROLE;




-- SCHEMA ACCESS


GRANT USAGE
ON SCHEMA UNIVERSITY_DB.UNIMART
TO ROLE UNI_STUDENT_ROLE;


GRANT USAGE
ON SCHEMA UNIVERSITY_DB.UNIMART
TO ROLE UNIVERSITY_ADMIN_ROLE;



-- VIEWER ROLE ACCESS

GRANT SELECT
ON TABLE UNIVERSITY_DB.UNIMART.DIM_STUDENT
TO ROLE UNI_STUDENT_ROLE;


GRANT SELECT
ON TABLE UNIVERSITY_DB.UNIMART.DIM_ATTENDANCE
TO ROLE UNI_STUDENT_ROLE;


GRANT SELECT
ON TABLE UNIVERSITY_DB.UNIMART.STUDENT_PERFORMANCE_SUMMARY
TO ROLE UNI_STUDENT_ROLE;


GRANT SELECT
ON TABLE UNIVERSITY_DB.UNIMART.PASS_PERCENTAGE_SUMMARY
TO ROLE UNI_STUDENT_ROLE;


GRANT SELECT
ON TABLE UNIVERSITY_DB.UNIMART.FACT_RESULT
TO ROLE UNI_STUDENT_ROLE;



-- UNIVERSITY ADMIN ROLE ACCESS


GRANT SELECT
ON ALL TABLES IN SCHEMA UNIVERSITY_DB.UNIMART
TO ROLE UNIVERSITY_ADMIN_ROLE;



-- CREATE MASKING POLICY FOR MARKS


CREATE OR REPLACE MASKING POLICY STUDENT_MARKS_POLICY

AS (val NUMBER)

RETURNS NUMBER ->

CASE

    WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN','UNIVERSITY_ADMIN_ROLE')

    THEN val

    ELSE NULL

END;



-- CREATE MASKING POLICY FOR AVG MARKS


CREATE OR REPLACE MASKING POLICY PERFORMANCE_POLICY

AS (val FLOAT)

RETURNS FLOAT ->

CASE

    WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN','UNIVERSITY_ADMIN_ROLE')

    THEN val

    ELSE NULL

END;



-- APPLY MASKING POLICY ON FACT TABLE


ALTER TABLE UNIVERSITY_DB.UNIMART.FACT_RESULT

MODIFY COLUMN marksObtained

SET MASKING POLICY STUDENT_MARKS_POLICY;




-- APPLY MASKING POLICY ON SUMMARY TABLE


-- REMOVE POLICY FROM COLUMN

ALTER TABLE UNIVERSITY_DB.UNIMART.STUDENT_PERFORMANCE_SUMMARY

MODIFY COLUMN avg_marks

UNSET MASKING POLICY;



-- DROP OLD POLICY

DROP MASKING POLICY IF EXISTS PERFORMANCE_POLICY;



-- CREATE CORRECT POLICY

CREATE OR REPLACE MASKING POLICY PERFORMANCE_POLICY

AS (val NUMBER(38,6))

RETURNS NUMBER(38,6) ->

CASE

    WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN','UNIVERSITY_ADMIN_ROLE')

    THEN val

    ELSE NULL

END;



-- APPLY POLICY AGAIN



ALTER TABLE UNIVERSITY_DB.UNIMART.STUDENT_PERFORMANCE_SUMMARY

MODIFY COLUMN avg_marks

SET MASKING POLICY PERFORMANCE_POLICY;



-- CREATE SAMPLE USERS


CREATE OR REPLACE USER VIEWER_USER

PASSWORD = 'Viewer@123'

DEFAULT_ROLE = UNI_STUDENT_ROLE

DEFAULT_WAREHOUSE = UNIVERSITY_WH

MUST_CHANGE_PASSWORD = FALSE;



CREATE OR REPLACE USER UNIVERSITY_ADMIN_USER

PASSWORD = 'Admin@123'

DEFAULT_ROLE = UNIVERSITY_ADMIN_ROLE

DEFAULT_WAREHOUSE = UNIVERSITY_WH

MUST_CHANGE_PASSWORD = FALSE;




-- ASSIGN ROLES TO USERS


GRANT ROLE UNI_STUDENT_ROLE
TO USER VIEWER_USER;


GRANT ROLE UNIVERSITY_ADMIN_ROLE
TO USER UNIVERSITY_ADMIN_USER;




-- ASSIGN ROLES TO CURRENT USER


GRANT ROLE UNI_STUDENT_ROLE
TO USER UMA3;


GRANT ROLE UNIVERSITY_ADMIN_ROLE
TO USER UMA3;




-- DISABLE CACHED RESULTS


ALTER SESSION SET USE_CACHED_RESULT = FALSE;




-- VERIFY ROLES


SHOW ROLES;




-- VERIFY USERS


SHOW USERS;




